"""Build and validate a Mitsuba 3 checkout with the custom penvmap emitter.

This script automates the local Windows-oriented workflow for:

1. choosing or creating a Mitsuba source checkout,
2. copying and registering the penvmap emitter source,
3. configuring and building Mitsuba with CMake,
4. enabling the expected polarized variants in mitsuba.conf,
5. discovering the built runtime and Python package layout,
6. validating that Mitsuba imports successfully, and
7. writing a small manifest plus runtime bootstrap information.

The main entry point is main(), which runs the build pipeline end to end and
exits with a non-zero status if any required step fails.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence


REPO_ROOT = Path(__file__).resolve().parent
EXTERNAL_DIR = REPO_ROOT / "external"
DEFAULT_MITSUBA_DIR = EXTERNAL_DIR / "mitsuba3"
LEGACY_FALLBACK_MITSUBA_DIR = EXTERNAL_DIR / "mitsuba3-source"
FALLBACK_MITSUBA_DIR = REPO_ROOT / ".mitsuba3-source"
BUILD_MANIFEST = REPO_ROOT / ".mitsuba-build.json"
BOOTSTRAP_MODULE = "penvmap_repo_sitecustomize"
PLUGIN_SOURCE = REPO_ROOT / "penvmap.cpp"
MITSUBA_GIT_URL = "https://github.com/mitsuba-renderer/mitsuba3"
PLUGIN_REGISTRATION = "add_plugin(penvmap         penvmap.cpp)"
SCALAR_VARIANT = "scalar_rgb"
LLVM_VARIANT = "llvm_ad_rgb_polarized"
CUDA_VARIANT = "cuda_ad_rgb_polarized"
REQUIRED_CMAKE_POLICY = "3.5"
REQUIRED_SOURCE_FILES = (
	"CMakeLists.txt",
	"src/emitters/CMakeLists.txt",
	"src/python/__init__.py",
	"ext/libjpeg/jdmainct.c",
	"ext/libpng/png.c",
	"ext/drjit/src/extra/autodiff.cpp",
)
DOCSTR_COMPATIBILITY_SCRIPT = """from __future__ import annotations
\nimport sys
from pathlib import Path
\n\ndef main() -> int:
	output = None
	for argument in reversed(sys.argv[1:]):
		if argument.endswith('.h'):
			output = Path(argument)
			break
	if output is None:
		output = Path.cwd() / 'docstr.h'
	output.parent.mkdir(parents=True, exist_ok=True)
	output.write_text('// Generated by compile_mitsuba3.py\n#pragma once\n', encoding='utf-8')
	return 0
\n\nif __name__ == '__main__':
	raise SystemExit(main())
"""


class BuildError(RuntimeError):
	pass


@dataclass(slots=True)
class WorkspacePaths:
	mitsuba_dir: Path
	build_dir: Path
	plugin_destination: Path
	emitters_cmake_lists: Path
	mitsuba_conf: Path


def workspace_paths_for(base_dir: Path) -> WorkspacePaths:
	build_dir = base_dir / "build"
	return WorkspacePaths(
		mitsuba_dir=base_dir,
		build_dir=build_dir,
		plugin_destination=base_dir / "src" / "emitters" / "penvmap.cpp",
		emitters_cmake_lists=base_dir / "src" / "emitters" / "CMakeLists.txt",
		mitsuba_conf=build_dir / "mitsuba.conf",
	)


@dataclass(slots=True)
class BuildLayout:
	python_root: Path
	package_dir: Path
	runtime_dir: Path
	plugin_path: Path
	llvm_c_api: Path | None
	enabled_variants: list[str]
	validation_order: list[str]


def log(message: str) -> None:
	print(f"[compile_mitsuba3] {message}")


def run_command(
	args: Sequence[str | Path],
	*,
	cwd: Path | None = None,
	env: dict[str, str] | None = None,
	capture_output: bool = False,
) -> str:
	command = [str(arg) for arg in args]
	log(f"run: {subprocess.list2cmdline(command)}")
	completed = subprocess.run(
		command,
		cwd=cwd,
		env=env,
		text=True,
		capture_output=capture_output,
		check=False,
	)
	if completed.returncode != 0:
		details = ""
		if capture_output:
			chunks = [chunk.strip() for chunk in (completed.stdout, completed.stderr) if chunk.strip()]
			if chunks:
				details = "\n\n" + "\n\n".join(chunks[-2:])
		raise BuildError(
			f"Command failed with exit code {completed.returncode}: "
			f"{subprocess.list2cmdline(command)}{details}"
		)
	return completed.stdout if capture_output else ""


def prepend_path(env: dict[str, str], name: str, path: Path) -> None:
	current = env.get(name, "")
	path_str = str(path)
	entries = [entry for entry in current.split(os.pathsep) if entry]
	if path_str in entries:
		return
	env[name] = path_str if not current else path_str + os.pathsep + current


def ensure_required_tools() -> None:
	missing = [tool for tool in ("git", "cmake") if shutil.which(tool) is None]
	if missing:
		joined = ", ".join(missing)
		raise BuildError(f"Missing required tools on PATH: {joined}")


def has_mitsuba_source_tree(path: Path) -> bool:
	if not path.exists():
		return False
	for relative_path in REQUIRED_SOURCE_FILES:
		if not (path / relative_path).exists():
			return False
	return True


def remove_stale_checkout(path: Path) -> bool:
	if not path.exists():
		return True
	names = {child.name for child in path.iterdir()}
	if not names or names <= {"build"}:
		log(f"Removing incomplete Mitsuba directory: {path}")
		try:
			shutil.rmtree(path)
		except PermissionError as exc:
			log(f"Could not remove {path}: {exc}")
			return False
		return True
	raise BuildError(
		f"{path} exists but is not a usable Mitsuba source checkout. "
		"Remove it manually or convert it into a full checkout, then rerun the script."
	)


def prepare_checkout_directory() -> WorkspacePaths:
	for candidate in (DEFAULT_MITSUBA_DIR, FALLBACK_MITSUBA_DIR, LEGACY_FALLBACK_MITSUBA_DIR):
		if has_mitsuba_source_tree(candidate):
			log(f"Using existing Mitsuba checkout: {candidate}")
			return workspace_paths_for(candidate)

	if DEFAULT_MITSUBA_DIR.exists() and not remove_stale_checkout(DEFAULT_MITSUBA_DIR):
		for candidate in (FALLBACK_MITSUBA_DIR, LEGACY_FALLBACK_MITSUBA_DIR):
			if candidate.exists() and not has_mitsuba_source_tree(candidate):
				if not remove_stale_checkout(candidate):
					raise BuildError(
						"Both Mitsuba checkout locations are locked or incomplete. "
						"Close programs using the fallback checkout and rerun the script."
					)
		log(f"Using fallback Mitsuba checkout directory: {FALLBACK_MITSUBA_DIR}")
		return workspace_paths_for(FALLBACK_MITSUBA_DIR)

	for candidate in (FALLBACK_MITSUBA_DIR, LEGACY_FALLBACK_MITSUBA_DIR):
		if candidate.exists() and not has_mitsuba_source_tree(candidate):
			if not remove_stale_checkout(candidate):
				raise BuildError(
					f"Could not clear fallback Mitsuba directory: {candidate}. "
					"Close programs using it and rerun the script."
				)

	return workspace_paths_for(DEFAULT_MITSUBA_DIR)


def ensure_mitsuba_checkout(workspace: WorkspacePaths) -> None:
	if has_mitsuba_source_tree(workspace.mitsuba_dir):
		git_dir = workspace.mitsuba_dir / ".git"
		if git_dir.exists():
			log("Updating Mitsuba submodules")
			run_command(["git", "-C", workspace.mitsuba_dir, "submodule", "update", "--init", "--recursive"])
		return

	if not remove_stale_checkout(workspace.mitsuba_dir):
		raise BuildError(
			f"Could not clear incomplete Mitsuba directory: {workspace.mitsuba_dir}. "
			"Close programs using it and rerun the script."
		)
	workspace.mitsuba_dir.parent.mkdir(parents=True, exist_ok=True)
	log("Cloning Mitsuba3 stable with submodules")
	run_command(["git", "clone", "-b", "stable", "--recursive", MITSUBA_GIT_URL, workspace.mitsuba_dir])


def copy_if_changed(source: Path, destination: Path, *, relative_root: Path | None = None) -> None:
	if not source.exists():
		raise BuildError(f"Missing custom plugin source: {source}")
	source_text = source.read_text(encoding="utf-8")
	if destination.exists() and destination.read_text(encoding="utf-8") == source_text:
		return
	destination.parent.mkdir(parents=True, exist_ok=True)
	destination.write_text(source_text, encoding="utf-8")
	if relative_root is not None:
		log(f"Updated {destination.relative_to(relative_root)}")
	else:
		log(f"Updated {destination}")


def ensure_plugin_registration(workspace: WorkspacePaths) -> None:
	if not workspace.emitters_cmake_lists.exists():
		raise BuildError(f"Missing emitter CMake file: {workspace.emitters_cmake_lists}")
	text = workspace.emitters_cmake_lists.read_text(encoding="utf-8")
	if PLUGIN_REGISTRATION in text:
		return
	anchor = 'set(MI_PLUGIN_TARGETS "${MI_PLUGIN_TARGETS}" PARENT_SCOPE)'
	if anchor not in text:
		raise BuildError(f"Could not find plugin registration anchor in {workspace.emitters_cmake_lists}")
	newline = "\r\n" if "\r\n" in text else "\n"
	updated = text.replace(anchor, f"{PLUGIN_REGISTRATION}{newline}{anchor}")
	workspace.emitters_cmake_lists.write_text(updated, encoding="utf-8")
	log("Registered penvmap plugin in Mitsuba CMakeLists.txt")


def install_penvmap_plugin(workspace: WorkspacePaths) -> None:
	copy_if_changed(PLUGIN_SOURCE, workspace.plugin_destination, relative_root=workspace.mitsuba_dir)
	ensure_plugin_registration(workspace)


def detect_visual_studio_generator() -> str:
	output = run_command(["cmake", "--help"], capture_output=True)
	matches: list[tuple[int, int, str]] = []
	pattern = re.compile(r"^[\s*]*(Visual Studio (?P<major>\d+) (?P<year>\d{4}))\s*=", re.MULTILINE)
	for match in pattern.finditer(output):
		matches.append((int(match.group("major")), int(match.group("year")), match.group(1)))
	if not matches:
		raise BuildError("CMake did not report any Visual Studio generators.")
	matches.sort()
	generator = matches[-1][2]
	log(f"Selected generator: {generator}")
	return generator


def read_cached_generator(workspace: WorkspacePaths) -> str | None:
	cache_file = workspace.build_dir / "CMakeCache.txt"
	if not cache_file.exists():
		return None
	for line in cache_file.read_text(encoding="utf-8", errors="ignore").splitlines():
		if line.startswith("CMAKE_GENERATOR:INTERNAL=") or line.startswith("CMAKE_GENERATOR:STRING="):
			return line.split("=", 1)[1].strip()
	return None


def clear_stale_cmake_cache(workspace: WorkspacePaths, expected_generator: str) -> None:
	cached_generator = read_cached_generator(workspace)
	if cached_generator is None or cached_generator == expected_generator:
		return
	cache_file = workspace.build_dir / "CMakeCache.txt"
	cmake_files = workspace.build_dir / "CMakeFiles"
	if cache_file.exists():
		log(f"Removing stale cache for generator switch: {cached_generator} -> {expected_generator}")
		cache_file.unlink()
	if cmake_files.exists():
		shutil.rmtree(cmake_files)


def configure_mitsuba(workspace: WorkspacePaths, generator: str) -> None:
	workspace.build_dir.mkdir(parents=True, exist_ok=True)
	clear_stale_cmake_cache(workspace, generator)
	run_command(
		[
			"cmake",
			"-S",
			workspace.mitsuba_dir,
			"-B",
			workspace.build_dir,
			"-G",
			generator,
			"-A",
			"x64",
			f"-DCMAKE_POLICY_VERSION_MINIMUM={REQUIRED_CMAKE_POLICY}",
			"-DCMAKE_POLICY_DEFAULT_CMP0175=OLD",
			"-DCMAKE_SUPPRESS_REGENERATION=ON",
			f"-DPython_EXECUTABLE={sys.executable}",
		]
	)
	if not workspace.mitsuba_conf.exists():
		raise BuildError(f"Mitsuba configure did not produce {workspace.mitsuba_conf}")


def detect_cuda_support() -> bool:
	if os.environ.get("CUDA_PATH") or os.environ.get("CUDA_HOME"):
		return True
	if shutil.which("nvcc") is not None:
		return True
	program_files = Path(os.environ.get("ProgramFiles", r"C:\Program Files"))
	cuda_root = program_files / "NVIDIA GPU Computing Toolkit" / "CUDA"
	return cuda_root.exists() and any(child.is_dir() for child in cuda_root.iterdir())


def replace_enabled_variants(text: str, variants: Sequence[str]) -> str:
	variant_text = ", ".join(f'"{variant}"' for variant in variants)
	pattern = re.compile(r'"enabled"\s*:\s*\[[^\]]*\]', re.DOTALL)
	updated, count = pattern.subn(f'"enabled": [{variant_text}]', text, count=1)
	if count != 1:
		raise BuildError("Could not update enabled variants in mitsuba.conf")
	return updated


def replace_python_default(text: str, variant: str) -> str:
	pattern = re.compile(r'"python-default"\s*:\s*"[^"]*"')
	updated, count = pattern.subn(f'"python-default": "{variant}"', text, count=1)
	if count != 1:
		raise BuildError("Could not update python-default in mitsuba.conf")
	return updated


def update_mitsuba_conf(workspace: WorkspacePaths) -> tuple[list[str], list[str], bool]:
	text = workspace.mitsuba_conf.read_text(encoding="utf-8")
	cuda_enabled = detect_cuda_support()
	enabled_variants = [SCALAR_VARIANT, LLVM_VARIANT]
	validation_order = [LLVM_VARIANT]
	if cuda_enabled:
		enabled_variants.append(CUDA_VARIANT)
		validation_order = [CUDA_VARIANT, LLVM_VARIANT]
	default_variant = validation_order[0]
	updated = replace_enabled_variants(text, enabled_variants)
	updated = replace_python_default(updated, default_variant)
	changed = updated != text
	if updated != text:
		workspace.mitsuba_conf.write_text(updated, encoding="utf-8")
		log(f"Updated mitsuba.conf with variants: {', '.join(enabled_variants)}")
	else:
		log("mitsuba.conf already contains the requested variants")
	return enabled_variants, validation_order, changed


def sync_python_files(source_root: Path, destination_root: Path) -> None:
	if not source_root.exists():
		return
	for source_path in source_root.rglob("*"):
		relative_path = source_path.relative_to(source_root)
		destination_path = destination_root / relative_path
		if source_path.is_dir():
			destination_path.mkdir(parents=True, exist_ok=True)
			continue
		if source_path.suffix not in {".py", ".pyi", ".pat", ".txt"}:
			continue
		destination_path.parent.mkdir(parents=True, exist_ok=True)
		shutil.copy2(source_path, destination_path)


def prepare_python_support_files(workspace: WorkspacePaths) -> None:
	drjit_source_root = workspace.mitsuba_dir / "ext" / "drjit" / "drjit"
	mitsuba_python_source_root = workspace.mitsuba_dir / "src" / "python"
	sync_python_files(drjit_source_root, workspace.build_dir / "Release" / "python" / "drjit")
	sync_python_files(mitsuba_python_source_root, workspace.build_dir / "Release" / "python" / "mitsuba")
	sync_python_files(mitsuba_python_source_root, workspace.build_dir / "src" / "python" / "python" / "mitsuba")

	compatibility_dir = workspace.mitsuba_dir / "ext" / "drjit" / "src" / "python"
	compatibility_dir.mkdir(parents=True, exist_ok=True)
	docstr_path = compatibility_dir / "docstr.py"
	if not docstr_path.exists():
		docstr_path.write_text(DOCSTR_COMPATIBILITY_SCRIPT, encoding="utf-8")
		log("Created compatibility docstr.py for Dr.Jit Python targets")


def build_mitsuba(workspace: WorkspacePaths) -> None:
	run_command(["cmake", "--build", workspace.build_dir, "--config", "Release"])


def locate_llvm_c_api() -> Path | None:
	candidates: list[Path] = []
	direct_env = os.environ.get("DRJIT_LIBLLVM_PATH")
	if direct_env:
		candidates.append(Path(direct_env))
	for variable in ("LLVM_DIR", "LLVM_PATH"):
		value = os.environ.get(variable)
		if value:
			root = Path(value)
			candidates.extend([root / "bin" / "LLVM-C.dll", root / "LLVM-C.dll"])
	for entry in os.environ.get("PATH", "").split(os.pathsep):
		if entry:
			candidates.append(Path(entry) / "LLVM-C.dll")
	home = Path.home()
	candidates.extend(
		[
			home / "Documents" / "LLVM" / "bin" / "LLVM-C.dll",
			Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "LLVM" / "bin" / "LLVM-C.dll",
			Path(os.environ.get("ProgramFiles(x86)", r"C:\Program Files (x86)")) / "LLVM" / "bin" / "LLVM-C.dll",
		]
	)
	for candidate in candidates:
		if candidate.exists():
			return candidate.resolve()
	return None


def find_candidate_paths(root: Path, pattern: str) -> list[Path]:
	return [path for path in root.rglob(pattern) if path.exists()]


def choose_preferred_path(paths: Iterable[Path], preferred_suffix: tuple[str, ...]) -> Path | None:
	items = list(paths)
	if not items:
		return None

	def score(path: Path) -> tuple[int, int]:
		suffix = tuple(path.parts[-len(preferred_suffix) :]) if len(path.parts) >= len(preferred_suffix) else ()
		matches = int(suffix == preferred_suffix)
		return (matches, -len(path.parts))

	return max(items, key=score)


def infer_runtime_dir(plugin_path: Path) -> Path:
	current = plugin_path.parent
	while current != current.parent:
		if current.name == "plugins":
			return current.parent
		current = current.parent
	raise BuildError(f"Could not infer runtime directory from plugin path: {plugin_path}")


def discover_build_layout(
	workspace: WorkspacePaths,
	enabled_variants: list[str],
	validation_order: list[str],
) -> BuildLayout:
	plugin_candidates = [
		path
		for path in find_candidate_paths(workspace.build_dir, "penvmap.dll")
		if "plugins" in path.parts and path.name == "penvmap.dll"
	]
	plugin_path = choose_preferred_path(plugin_candidates, ("Release", "plugins", "emitters", "penvmap.dll"))
	if plugin_path is None:
		raise BuildError("The Mitsuba build completed but penvmap.dll was not found in the build tree.")

	package_candidates = [
		path
		for path in find_candidate_paths(workspace.build_dir, "__init__.py")
		if path.parent.name == "mitsuba"
	]
	package_init = choose_preferred_path(package_candidates, ("python", "mitsuba", "__init__.py"))
	if package_init is None:
		raise BuildError("Could not locate the built Mitsuba Python package in the build tree.")

	setpath_candidates = find_candidate_paths(workspace.build_dir, "setpath.ps1")
	setpath_path = choose_preferred_path(setpath_candidates, ("Release", "setpath.ps1"))
	runtime_dir = setpath_path.parent if setpath_path is not None else infer_runtime_dir(plugin_path)
	package_dir = package_init.parent
	python_root = package_dir.parent
	llvm_c_api = locate_llvm_c_api()
	return BuildLayout(
		python_root=python_root,
		package_dir=package_dir,
		runtime_dir=runtime_dir,
		plugin_path=plugin_path,
		llvm_c_api=llvm_c_api,
		enabled_variants=enabled_variants,
		validation_order=validation_order,
	)


def write_build_manifest(layout: BuildLayout) -> None:
	manifest = {
		"runtime_dir": str(layout.runtime_dir),
		"python_root": str(layout.python_root),
		"package_dir": str(layout.package_dir),
		"plugin_path": str(layout.plugin_path),
		"enabled_variants": layout.enabled_variants,
		"validation_order": layout.validation_order,
		"llvm_c_api": str(layout.llvm_c_api) if layout.llvm_c_api is not None else None,
	}
	BUILD_MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
	log(f"Wrote runtime manifest: {BUILD_MANIFEST}")


def install_runtime_bootstrap() -> None:
	repo_bootstrap = REPO_ROOT / "sitecustomize.py"
	if not repo_bootstrap.exists():
		raise BuildError(f"Missing runtime bootstrap module: {repo_bootstrap}")
	bootstrap_file = Path(sys.prefix) / "sitecustomize.py"
	content = f"""from __future__ import annotations

import importlib.util
import sys
from pathlib import Path


bootstrap_path = Path(r\"{repo_bootstrap}\")
spec = importlib.util.spec_from_file_location(\"{BOOTSTRAP_MODULE}\", bootstrap_path)
if spec is None or spec.loader is None:
	raise RuntimeError(f\"Could not load Mitsuba bootstrap from {{bootstrap_path}}\")
module = importlib.util.module_from_spec(spec)
sys.modules.setdefault(\"{BOOTSTRAP_MODULE}\", module)
spec.loader.exec_module(module)
"""
	if bootstrap_file.exists() and bootstrap_file.read_text(encoding="utf-8") == content:
		return
	bootstrap_file.write_text(content, encoding="utf-8")
	log(f"Installed uv runtime bootstrap: {bootstrap_file}")


def validate_import(layout: BuildLayout) -> str:
	env = os.environ.copy()
	prepend_path(env, "PATH", layout.runtime_dir)
	prepend_path(env, "PATH", layout.package_dir)
	env["MITSUBA_DIR"] = str(layout.runtime_dir)

	llvm_c_api = layout.llvm_c_api
	if llvm_c_api is not None:
		env["DRJIT_LIBLLVM_PATH"] = str(llvm_c_api)
		prepend_path(env, "PATH", llvm_c_api.parent)

	code = f"""
import os
import sys
from pathlib import Path

python_root = Path({str(layout.python_root)!r})
runtime_dir = Path({str(layout.runtime_dir)!r})
package_dir = Path({str(layout.package_dir)!r})
validation_order = {layout.validation_order!r}

if str(python_root) not in sys.path:
	sys.path.insert(0, str(python_root))

handles = []
if hasattr(os, \"add_dll_directory\"):
	for path in (runtime_dir, package_dir):
		if path.exists():
			handles.append(os.add_dll_directory(str(path)))

import mitsuba as mi

errors = []
for variant in validation_order:
	try:
		mi.set_variant(variant)
		print(f\"module={{Path(mi.__file__).resolve()}}\")
		print(f\"variant={{variant}}\")
		break
	except Exception as exc:
		errors.append(f\"{{variant}}: {{exc}}\")
else:
	raise RuntimeError(\"; ".join(errors))
"""
	output = run_command([sys.executable, "-c", code], cwd=REPO_ROOT, env=env, capture_output=True)
	return output.strip()


def main() -> int:
	try:
		ensure_required_tools()
		workspace = prepare_checkout_directory()
		ensure_mitsuba_checkout(workspace)
		install_penvmap_plugin(workspace)
		generator = detect_visual_studio_generator()
		configure_mitsuba(workspace, generator)
		enabled_variants, validation_order, config_changed = update_mitsuba_conf(workspace)
		if config_changed:
			configure_mitsuba(workspace, generator)
		prepare_python_support_files(workspace)
		build_mitsuba(workspace)
		layout = discover_build_layout(workspace, enabled_variants, validation_order)
		validation_output = validate_import(layout)
		write_build_manifest(layout)
		install_runtime_bootstrap()
		log(f"plugin: {layout.plugin_path}")
		log(validation_output)
		return 0
	except BuildError as exc:
		print(f"error: {exc}", file=sys.stderr)
		return 1


if __name__ == "__main__":
	raise SystemExit(main())
